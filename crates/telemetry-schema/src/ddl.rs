use std::io;

pub const TEMPLATE: &str = include_str!("../../../infra/clickhouse/schema.sql.in");
pub const PARTICIPANT_TEMPLATE: &str =
    include_str!("../../../infra/clickhouse/participants.sql.in");
pub const BLOCK_ROWS: u32 = 64;
pub const POLL_MESSAGES: u32 = 32;
pub const FLUSH_MS: u32 = 2000;

pub struct ParticipantSchema<'a> {
    pub database: &'a str,
    pub bootstrap: &'a str,
    pub topic: &'a str,
    pub group: &'a str,
    pub partition_limit: u32,
}

impl ParticipantSchema<'_> {
    pub fn render(&self) -> io::Result<String> {
        let batching = Batching::for_partition_limit(self.partition_limit)?;
        let identifier = |s: &str| {
            !s.is_empty()
                && s.bytes()
                    .next()
                    .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
                && s.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
        };
        let kafka = |s: &str| {
            !s.is_empty()
                && s.bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b))
        };
        if !identifier(self.database)
            || !kafka(self.topic)
            || !kafka(self.group)
            || self.bootstrap.is_empty()
            || !self
                .bootstrap
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b"_.:,[]-".contains(&b))
        {
            return Err(io::Error::other("Invalid participant schema inputs"));
        }
        let mut sql = PARTICIPANT_TEMPLATE.to_owned();
        for (token, value) in [
            ("__DATABASE__", self.database),
            ("__KAFKA_BOOTSTRAP__", self.bootstrap),
            ("__PARTICIPANT_TOPIC__", self.topic),
            ("__PARTICIPANT_GROUP__", self.group),
            ("__PARTICIPANT_COLUMNS__", crate::PARTICIPANT_COLUMNS.trim()),
        ] {
            sql = sql.replace(token, value);
        }
        sql = sql
            .replace(
                "__PARTICIPANT_BLOCK_ROWS__",
                &batching.block_rows.to_string(),
            )
            .replace(
                "__PARTICIPANT_POLL_MESSAGES__",
                &batching.poll_messages.to_string(),
            );
        Ok(sql)
    }
}
/// Rows per insert from the recent topic. Its points lie within a day of the normalizer's
/// clock, so a block touches a few day partitions however many rows it holds. Larger
/// inserts create fewer parts: at matched load, doubling from 16K halved parts and merge CPU.
/// The cap sits above what one consumer gathers per flush, so the interval ends blocks.
pub const RECENT_BLOCK_ROWS: u32 = 98_304;
/// Each consumer flushes its own block, so splitting the topic across consumers shrinks
/// parts unless the interval grows with them. This bounds the added freshness delay.
pub const RECENT_FLUSH_MS: u32 = 4000;
// A poll of 16 packed messages can deliver up to 2,048 rows.
pub const RECENT_POLL_MESSAGES: u32 = 16;
/// Consumers reading the recent topic, one per normalized partition. Each parses and
/// inserts its own blocks; one consumer could not keep up at about 41k rows/s.
pub const RECENT_CONSUMERS: u32 = 3;
/// Settings both Kafka tables share; each adds its topic, group and batching.
const KAFKA_SETTINGS: &str = "    kafka_broker_list = '__KAFKA_BOOTSTRAP__',
    kafka_schema = 'recount.proto:AnalyticalPoint',
    format_protobuf_use_autogenerated_schema = 0,
    kafka_schema_registry_skip_bytes = 0,
    kafka_skip_broken_messages = 0,
    kafka_handle_error_mode = 'default',
    input_format_allow_errors_num = 0,
    input_format_allow_errors_ratio = 0,
    kafka_commit_every_batch = 0,
    kafka_commit_on_select = 0,
    kafka_thread_per_consumer = 1,";

pub struct Batching {
    pub block_rows: u32,
    pub poll_messages: u32,
}

impl Batching {
    pub fn for_partition_limit(partitions: u32) -> io::Result<Self> {
        if partitions == 0 {
            return Err(io::Error::other("positive insert partition limit required"));
        }
        let block_rows = partitions.min(BLOCK_ROWS);
        // KafkaSource checks the row target after finishing an already-fetched poll.
        let poll_messages = POLL_MESSAGES.min(partitions - block_rows + 1);
        Ok(Self {
            block_rows,
            poll_messages,
        })
    }

    pub fn maximum_rows(&self) -> u32 {
        self.block_rows + self.poll_messages - 1
    }
}

pub struct Schema<'a> {
    pub database: &'a str,
    pub bootstrap: &'a str,
    pub topic: &'a str,
    pub group: &'a str,
    pub late_topic: &'a str,
    pub late_group: &'a str,
    pub partition_limit: u32,
    pub poll_ms: u32,
    pub flush_ms: u32,
    pub if_not_exists: bool,
}

impl Schema<'_> {
    pub fn render(&self) -> io::Result<String> {
        self.render_with_dead_letter(
            &format!("{}.dead-letter", self.topic),
            &format!("{}-dead-letter", self.group),
        )
    }

    pub fn render_with_dead_letter(&self, topic: &str, group: &str) -> io::Result<String> {
        let batching = Batching::for_partition_limit(self.partition_limit)?;
        let identifier = |value: &str| {
            !value.is_empty()
                && value
                    .bytes()
                    .next()
                    .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
                && value
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'_')
        };
        let kafka_name = |value: &str| {
            !value.is_empty()
                && value
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b))
        };
        if !identifier(self.database)
            || !kafka_name(self.topic)
            || !kafka_name(self.group)
            || !kafka_name(self.late_topic)
            || !kafka_name(self.late_group)
            || !kafka_name(topic)
            || !kafka_name(group)
            || [self.topic, self.late_topic].contains(&topic)
            || [self.group, self.late_group].contains(&group)
            || self.late_topic == self.topic
            || self.late_group == self.group
            || self.bootstrap.is_empty()
            || !self
                .bootstrap
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b"_.:,[]-".contains(&b))
            || self.poll_ms == 0
            || self.poll_ms > i32::MAX as u32
            || self.flush_ms == 0
            || self.flush_ms > i32::MAX as u32
        {
            return Err(io::Error::other("invalid ClickHouse schema inputs"));
        }
        let columns = crate::KAFKA_COLUMNS.trim();
        if columns.is_empty() || columns.contains(';') || columns.contains("__") {
            return Err(io::Error::other("invalid generated columns"));
        }
        let mut sql = TEMPLATE.replace("__KAFKA_SETTINGS__", KAFKA_SETTINGS);
        for (token, value) in [
            ("__DATABASE__", self.database.to_owned()),
            (
                "__CREATE_GUARD__",
                if self.if_not_exists {
                    "IF NOT EXISTS "
                } else {
                    ""
                }
                .to_owned(),
            ),
            ("__KAFKA_COLUMNS__", columns.to_owned()),
            ("__DELIVERY_COLUMNS__", crate::DELIVERY_COLUMNS.to_owned()),
            (
                "__DELIVERY_CONTEXT_COLUMNS__",
                crate::DELIVERY_CONTEXT_COLUMNS.to_owned(),
            ),
            ("__STREAM_COLUMNS__", crate::STREAM_COLUMNS.to_owned()),
            ("__POINT_COLUMNS__", crate::POINT_COLUMNS.to_owned()),
            ("__POINT_SELECT__", crate::POINT_SELECT.to_owned()),
            ("__SERIES_COLUMNS__", crate::SERIES_COLUMNS.to_owned()),
            ("__SERIES_SELECT__", crate::SERIES_SELECT.to_owned()),
            ("__KAFKA_BOOTSTRAP__", self.bootstrap.to_owned()),
            ("__NORMALIZED_TOPIC__", self.topic.to_owned()),
            ("__CONSUMER_GROUP__", self.group.to_owned()),
            ("__LATE_TOPIC__", self.late_topic.to_owned()),
            ("__LATE_CONSUMER_GROUP__", self.late_group.to_owned()),
            ("__DEAD_LETTER_TOPIC__", topic.to_owned()),
            ("__DEAD_LETTER_GROUP__", group.to_owned()),
            ("__RECENT_BLOCK_ROWS__", RECENT_BLOCK_ROWS.to_string()),
            ("__RECENT_POLL_MESSAGES__", RECENT_POLL_MESSAGES.to_string()),
            ("__RECENT_CONSUMERS__", RECENT_CONSUMERS.to_string()),
            ("__RECENT_FLUSH_MS__", RECENT_FLUSH_MS.to_string()),
            ("__BLOCK_ROWS__", batching.block_rows.to_string()),
            ("__POLL_MESSAGES__", batching.poll_messages.to_string()),
            ("__POLL_MS__", self.poll_ms.to_string()),
            ("__FLUSH_MS__", self.flush_ms.to_string()),
        ] {
            sql = sql.replace(token, &value);
        }
        if sql.contains("__") {
            return Err(io::Error::other("unresolved DDL placeholder"));
        }
        Ok(sql)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn participant_batches_respect_small_insert_partition_guards() {
        for limit in [1, 2, 8, 16, 128] {
            let batching = Batching::for_partition_limit(limit).unwrap();
            let sql = ParticipantSchema {
                database: "disposable",
                bootstrap: "kafka:9092",
                topic: "test.participants",
                group: "test.participants.consumer",
                partition_limit: limit,
            }
            .render()
            .unwrap();
            assert!(sql.contains(&format!("kafka_max_block_size = {}", batching.block_rows)));
            assert!(sql.contains(&format!(
                "kafka_poll_max_batch_size = {}",
                batching.poll_messages
            )));
            assert!(batching.maximum_rows() <= limit);
            assert!(sql.contains("environment_variable String"));
            assert!(sql.contains("process_resource_id Nullable(String)"));
            assert!(!sql.contains("cgroup_"));
            assert!(!sql.contains("launcher_claim_id"));
            assert!(!sql.contains("exit_code"));
        }
    }

    #[test]
    fn isolated_names_and_strict_object_creation_are_rendered_without_sql_injection() {
        let mut schema = Schema {
            database: "disposable",
            bootstrap: "kafka:9092",
            topic: "test.normalized",
            group: "test.consumer",
            late_topic: "test.late",
            late_group: "test.late-consumer",
            partition_limit: 128,
            poll_ms: 100,
            flush_ms: 1000,
            if_not_exists: false,
        };
        let sql = schema.render().unwrap();
        assert!(sql.contains("CREATE TABLE disposable.metric_points"));
        assert!(sql.contains("kafka_group_name = 'test.consumer'"));
        assert!(sql.contains("kafka_topic_list = 'test.normalized'"));
        assert!(sql.contains("kafka_topic_list = 'test.late'"));
        assert!(sql.contains("kafka_group_name = 'test.late-consumer'"));
        assert!(sql.contains("CREATE TABLE disposable.late_kafka"));
        assert!(sql.contains(&format!(
            "TO disposable.metric_points AS SELECT {} FROM disposable.late_kafka",
            crate::POINT_SELECT
        )));
        let series = sql
            .split_once("CREATE TABLE disposable.metric_series\n")
            .unwrap()
            .1
            .split(';')
            .next()
            .unwrap();
        assert!(series.contains("\nORDER BY (project_id, metric_name, resource_id, series_id)\n"));
        assert!(sql.contains("index_granularity = 1024, merge_max_block_size = 8192, merge_max_block_size_bytes = 10485760"));
        assert!(sql.contains("kafka_max_block_size = 98304"));
        assert_eq!(sql.matches("kafka_flush_interval_ms = 4000;").count(), 1);
        assert_eq!(sql.matches("kafka_num_consumers = 3,").count(), 1);
        assert_eq!(sql.matches("kafka_num_consumers = 1,").count(), 2);
        assert!(sql.contains("kafka_topic_list = 'test.normalized.dead-letter'"));
        assert!(sql.contains("kafka_max_block_size = 64,"));
        assert_eq!(sql.matches("kafka_format = 'ProtobufSingle'").count(), 1);
        assert_eq!(sql.matches("kafka_format = 'Protobuf'").count(), 1);
        assert!(!sql.contains("telemetry."));
        assert!(!sql.contains("__"));
        schema.database = "other; DROP DATABASE telemetry";
        assert!(schema.render().is_err());
        schema.database = "disposable";
        schema.group = "consumer'";
        assert!(schema.render().is_err());
        schema.group = "test.consumer";
        schema.late_topic = "test.normalized";
        assert!(schema.render().is_err());
    }

    #[test]
    fn complete_poll_overshoot_stays_within_the_insert_partition_guard() {
        for partitions in [1, 2, 32, 64, 65, 95, 128, 16384] {
            let batching = Batching::for_partition_limit(partitions).unwrap();
            assert!(batching.block_rows > 0 && batching.poll_messages > 0);
            assert!(batching.maximum_rows() <= partitions);
        }
        let batching = Batching::for_partition_limit(128).unwrap();
        assert_eq!(batching.block_rows, 64);
        assert_eq!(batching.poll_messages, 32);
        assert_eq!(batching.maximum_rows(), 95);
        assert!(Batching::for_partition_limit(0).is_err());
    }
}
