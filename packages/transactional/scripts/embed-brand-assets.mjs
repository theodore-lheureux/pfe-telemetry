import { readFile, writeFile } from "node:fs/promises";

const asset = async (name) =>
	(await readFile(new URL(`../assets/${name}`, import.meta.url))).toString(
		"base64",
	);
const light = await asset("recount-lockup-on-light.png");
const symbol = await asset("recount-symbol-teal.png");
await writeFile(
	new URL("../src/brand-assets.ts", import.meta.url),
	`// Generated by scripts/embed-brand-assets.mjs for email clients that cannot render SVG.
export const emailBrandAssets = {
	light:
		${JSON.stringify(light)},
	symbol:
		${JSON.stringify(symbol)},
} as const;
`,
);
